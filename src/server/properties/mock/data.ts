// A couple of stable pseudo-random helpers so the fixtures look varied but never change.
const hash = (str: string) => {
  let h = 0
  for (let i = 0; i < str.length; i++) h = (h * 31 + str.charCodeAt(i)) | 0
  return Math.abs(h)
}

